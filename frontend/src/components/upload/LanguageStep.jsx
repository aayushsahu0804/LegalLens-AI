import React, { useState } from 'react';
import { SUPPORTED_LANGUAGES } from '../../constants/languages';

export default function LanguageStep({ selectedLanguage, onLanguageSelect }) {
  const [searchQuery, setSearchQuery] = useState('');

  const filteredLanguages = SUPPORTED_LANGUAGES.filter((lang) => {
    const query = searchQuery.toLowerCase().trim();
    if (!query) return true;
    return (
      lang.label.toLowerCase().includes(query) ||
      lang.nativeLabel.toLowerCase().includes(query) ||
      lang.code.toLowerCase().includes(query)
    );
  });

  return (
    <div className="space-y-6">
      {/* Step Header */}
      <div className="text-center max-w-xl mx-auto space-y-2">
        <h2 className="text-2xl sm:text-3xl font-bold text-white tracking-tight">
          What language should LegalLens use?
        </h2>
        <p className="text-sm sm:text-base text-zinc-400 leading-relaxed">
          Choose the language you prefer for executive summaries, simplified explanations, and risk briefings generated by LegalLens AI.
        </p>
      </div>

      {/* Search and count filter */}
      <div className="max-w-md mx-auto relative">
        <div className="absolute inset-y-0 left-0 pl-3.5 flex items-center pointer-events-none">
          <svg className="w-4 h-4 text-zinc-500" fill="none" stroke="currentColor" viewBox="0 0 24 24">
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth="2" d="M21 21l-6-6m2-5a7 7 0 11-14 0 7 7 0 0114 0z" />
          </svg>
        </div>
        <input
          type="text"
          value={searchQuery}
          onChange={(e) => setSearchQuery(e.target.value)}
          placeholder="Filter languages (e.g. English, Español, हिन्दी)..."
          className="w-full pl-10 pr-4 py-2.5 rounded-xl bg-zinc-900/80 border border-zinc-700/80 text-sm text-white placeholder-zinc-500 focus:outline-none focus:border-indigo-500 focus:ring-1 focus:ring-indigo-500/50"
        />
        {searchQuery && (
          <button
            type="button"
            onClick={() => setSearchQuery('')}
            className="absolute inset-y-0 right-0 pr-3.5 flex items-center text-xs text-zinc-400 hover:text-white"
          >
            Clear
          </button>
        )}
      </div>

      {/* Languages Grid */}
      <div
        role="radiogroup"
        aria-label="Select preferred analysis language"
        className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-3.5 max-w-4xl mx-auto"
      >
        {filteredLanguages.map((lang) => {
          const isSelected = selectedLanguage === lang.code;

          return (
            <div
              key={lang.code}
              role="radio"
              aria-checked={isSelected}
              tabIndex={0}
              onClick={() => onLanguageSelect(lang.code)}
              onKeyDown={(e) => {
                if (e.key === ' ' || e.key === 'Enter') {
                  e.preventDefault();
                  onLanguageSelect(lang.code);
                }
              }}
              className={`group relative rounded-2xl p-4 cursor-pointer transition-all duration-200 flex items-center justify-between border focus:outline-none focus-visible:ring-2 focus-visible:ring-indigo-500 ${
                isSelected
                  ? 'bg-gradient-to-br from-indigo-950/70 to-zinc-900 border-indigo-500 shadow-[0_0_20px_-5px_rgba(99,102,241,0.4)]'
                  : 'bg-zinc-900/40 border-white/[0.08] hover:border-zinc-700/80 hover:bg-zinc-900/70'
              }`}
            >
              <div className="flex items-center gap-3 min-w-0">
                <span className="text-2xl shrink-0" role="img" aria-label={lang.label}>
                  {lang.flag}
                </span>
                <div className="min-w-0">
                  <div className="text-sm font-semibold text-white truncate">
                    {lang.label}
                  </div>
                  <div className="text-xs text-zinc-400 font-sans truncate">
                    {lang.nativeLabel}
                  </div>
                </div>
              </div>

              {/* Radio Indicator */}
              <div
                className={`w-5 h-5 rounded-full border flex items-center justify-center shrink-0 transition-all ${
                  isSelected
                    ? 'border-indigo-400 bg-indigo-600'
                    : 'border-zinc-700 bg-zinc-900 group-hover:border-zinc-500'
                }`}
              >
                {isSelected && <div className="w-2 h-2 rounded-full bg-white" />}
              </div>
            </div>
          );
        })}
      </div>

      {filteredLanguages.length === 0 && (
        <div className="text-center py-8 text-zinc-500 text-sm">
          No languages matching "{searchQuery}".
        </div>
      )}

      {/* Info Callout */}
      <div className="max-w-2xl mx-auto p-4 rounded-xl bg-zinc-950/60 border border-zinc-800 text-xs text-zinc-400 text-center">
        <span>
          💡 <strong className="text-zinc-300 font-medium">Extensible Multilingual Engine:</strong> LegalLens will pass this language parameter directly into the AI prompt pipeline to ensure clear explanations in your native tongue.
        </span>
      </div>
    </div>
  );
}
